def check(font):
    rows = {len(g) for g in font.values()}
    assert len(rows) == 1, f"glyphs disagree on height: {rows}"
    for ch, g in font.items():
        widths = {len(r) for r in g}
        assert len(widths) == 1, f"glyph {ch!r} has ragged rows {widths}"


